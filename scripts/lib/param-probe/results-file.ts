import type {
	ParameterProbeResults,
	ProbeRoute,
	RouteProbe,
} from "../../../src/models/parameter-probe";

// Reads and writes src/models/parameter-probe.generated.ts (roadmap 2.4a). The output is sorted
// and formatted the way Biome would format it, so re-running with the same results changes nothing.

/** Replaces one model's route entry and keeps everything else. Returns a new object. */
export function mergeRouteProbe(
	existing: ParameterProbeResults,
	gatewayId: string,
	route: ProbeRoute,
	probe: RouteProbe,
): ParameterProbeResults {
	return {
		...existing,
		[gatewayId]: { ...existing[gatewayId], [route]: probe },
	};
}

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;

function key(name: string): string {
	return IDENTIFIER.test(name) ? name : JSON.stringify(name);
}

function sortedEntries<T>(record: Readonly<Record<string, T>>): [string, T][] {
	return Object.entries(record)
		.filter(([, value]) => value !== undefined)
		.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
}

/** TypeScript source for an object literal, one property a line, tabs, trailing commas. */
export function toSource(value: unknown, depth = 0): string {
	if (typeof value !== "object" || value === null || Array.isArray(value))
		return JSON.stringify(value);
	const entries = sortedEntries(value as Record<string, unknown>);
	if (entries.length === 0) return "{}";
	const indent = "\t".repeat(depth + 1);
	const lines = entries.map(
		([name, child]) => `${indent}${key(name)}: ${toSource(child, depth + 1)},`,
	);
	return `{\n${lines.join("\n")}\n${"\t".repeat(depth)}}`;
}

export function renderResultsFile(results: ParameterProbeResults): string {
	return [
		"// Generated by `bun scripts/probe-params.ts` (roadmap 2.4a). Don't edit by hand: re-run the probe.",
		'import type { ParameterProbeResults } from "./parameter-probe";',
		"",
		`export const PARAMETER_PROBE: ParameterProbeResults = ${toSource(results)};`,
		"",
	].join("\n");
}
